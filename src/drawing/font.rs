//! A tiny built-in 5×7 bitmap font.
//!
//! VSE has no dependency on a font-rasterization engine: on-screen text
//! (instructions, labels, feedback) is drawn as filled rectangles through the
//! existing flat-color pipeline, one rect per lit pixel. That keeps text off any
//! texture-upload path and needs no bundled font asset.
//!
//! Glyphs are defined as ASCII-art so the source is self-documenting and
//! verifiable at a glance. The set covers `A`–`Z`, `0`–`9`, space, and common
//! punctuation; lowercase is mapped to uppercase. Unknown characters render as
//! an outlined box.

/// Glyph width in font pixels.
pub(crate) const FONT_W: usize = 5;
/// Glyph height in font pixels.
pub(crate) const FONT_H: usize = 7;
/// Blank columns inserted between glyphs, in font pixels.
pub(crate) const FONT_TRACKING: usize = 1;

/// Return the on/off pixel grid for a character (uppercased first).
pub(crate) fn glyph(c: char) -> [[bool; FONT_W]; FONT_H] {
    let pat = pattern(c.to_ascii_uppercase());
    let mut out = [[false; FONT_W]; FONT_H];
    for (r, row) in pat.iter().enumerate() {
        for (i, ch) in row.chars().take(FONT_W).enumerate() {
            out[r][i] = ch == '#';
        }
    }
    out
}

/// Advance width of a string in font pixels (glyphs + tracking).
pub(crate) fn text_width_px(text: &str) -> usize {
    let n = text.chars().count();
    if n == 0 {
        0
    } else {
        n * FONT_W + (n - 1) * FONT_TRACKING
    }
}


#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyph_dimensions() {
        let g = glyph('A');
        assert_eq!(g.len(), FONT_H);
        assert_eq!(g[0].len(), FONT_W);
    }

    #[test]
    fn a_crossbar_is_lit() {
        // Row 3 of 'A' is the full crossbar "#####".
        let g = glyph('A');
        assert_eq!(g[3], [true, true, true, true, true]);
        // Row 0 is ".###.".
        assert_eq!(g[0], [false, true, true, true, false]);
    }

    #[test]
    fn lowercase_maps_to_uppercase() {
        assert_eq!(glyph('a'), glyph('A'));
    }

    #[test]
    fn space_is_blank() {
        let g = glyph(' ');
        assert!(g.iter().all(|row| row.iter().all(|&on| !on)));
    }

    #[test]
    fn text_width_accounts_for_tracking() {
        // 3 glyphs: 3*5 + 2*1 tracking = 17.
        assert_eq!(text_width_px("ABC"), 3 * FONT_W + 2 * FONT_TRACKING);
        assert_eq!(text_width_px(""), 0);
    }
}
